"""Numeric constants ported verbatim from espeak-ng ``src/libespeak-ng/translate.h``.

These values are the load-bearing backbone of byte-for-byte compatibility: the rule
compiler emits them, the matcher consumes them, and the renderer keys off them. Keep
the names identical to upstream so the port maps 1:1.

Reference: espeak-ng 1.52.0 (commit 4870adfa25b1a32b4361592f1be8a40337c58d6c).
"""


def L(c1, c2):
    """Combine two characters into an integer translator name (translate.h L())."""
    return (ord(c1) << 8) + ord(c2)


def L3(c1, c2, c3):
    return (ord(c1) << 16) + (ord(c2) << 8) + ord(c3)


def L4(c1, c2, c3, c4):
    return (ord(c1) << 24) + (ord(c2) << 16) + (ord(c3) << 8) + ord(c4)


